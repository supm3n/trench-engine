std::optional<std::array<DustPoint, 6>> vehicle_dust_points(int nation, int type, int size, int orient) {
    if (nation < 0 || nation > 4 || orient < 0 || orient > 7) return std::nullopt;
    const Lin(*t)[2] = nullptr;
    if (type == 0xb) {
        t = nation == 1 ? kT11b[orient] : nation >= 3 ? kT11c[orient] : kT11a[orient];
    } else if (type == 0xc) {
        t = nation >= 3 ? kT12b[orient] : kT12a[orient];
    } else if (type == 0xd) {
        t = kT13[orient];
    } else if (type == 0x18) {
        t = kT24[orient];
    } else {
        return std::nullopt;
    }
    const auto S = static_cast<double>(static_cast<float>(size * static_cast<double>(0.4f)));
    std::array<DustPoint, 6> p;
    for (std::size_t k = 0; k < 6; ++k) {
        p[k].x = static_cast<float>(t[k][0].a * S + t[k][0].b);
        p[k].y = static_cast<float>(t[k][1].a * S + t[k][1].b);
    }
    return p;
}

